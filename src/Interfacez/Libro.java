    private void btnregistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnregistrarActionPerformed
        String autor = txtautor.getText();
        String titulo = txttitulo.getText();
        String editorial = txteditorial.getText();
        String materia = txtmateria.getText();
        int stock;
        // Validar que stock sea un número entero
        try {
            stock = Integer.parseInt(txtstock.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "EL STOCK DEBE SER UN NUMERO ENTERO");
            return; // Salir del método sin intentar registrar
        }
        float precio;
        // Validar que precio sea un número 
        try {
            precio= Float.parseFloat(txtprecio.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "EL STOCK DEBE SER UN NUMERO");
            return; // Salir del método sin intentar registrar
        }

        ConexionLibro co = new ConexionLibro();
        int respuesta = co.Rlibro(autor, titulo, editorial, materia, precio, stock);

        if(respuesta == 1) {
            JOptionPane.showMessageDialog(null, "PRODUCTO REGISTRADO");
            cargartabla();
        } else {
            JOptionPane.showMessageDialog(null, "ERROR AL REGISTRAR PRODUCTO");
        }
    }//GEN-LAST:event_btnregistrarActionPerformed

    private void TablaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TablaMouseClicked
            try {
            int fila=Tabla.getSelectedRow();
            int id=Integer.parseInt(Tabla.getValueAt(fila,0).toString());
            PreparedStatement ps;
            ResultSet res;
            ConexionLibro co=new ConexionLibro();
            Connection con=co.getConnection();
            ps = con.prepareStatement("select autor,titulo,editorial,materia,precio,stock from libro where id_libro=?");
            ps.setInt(1,id);
            res=ps.executeQuery();
            
            while(res.next()) {
                txtidlibro.setText(String.valueOf(id));
                txtautor.setText(res.getString("autor"));
                txttitulo.setText(res.getString("titulo"));
                txteditorial.setText(res.getString("editorial"));
                txtmateria.setText(res.getString("materia"));
                txtprecio.setText(res.getString("precio"));
                txtstock.setText(res.getString("stock"));
            }
        } catch(Exception e) {
            JOptionPane.showMessageDialog(null,e.toString());
        }
    }//GEN-LAST:event_TablaMouseClicked

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
        int idlibro = Integer.parseInt(txtidlibro.getText()); 
        
        ConexionLibro co=new ConexionLibro();
        
        int respuesta=co.Elibro(idlibro); 
        if (respuesta==1) {
        JOptionPane.showMessageDialog(null, "PRODUCTO ELIMINADO");
        limpiar();
        cargartabla();
        }else{
        JOptionPane.showMessageDialog(null, "ERROR AL ELIMINAR PRODUCTO");
        } 
    }//GEN-LAST:event_btneliminarActionPerformed

